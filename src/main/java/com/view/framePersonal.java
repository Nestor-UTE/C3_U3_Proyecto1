    private void tablaPersonalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaPersonalMouseClicked
        // TODO add your handling code here:
        int fila = tablaPersonal.getSelectedRow();
        
        lbId.setText(tablaPersonal.getValueAt(fila, 0) .toString());
        txtNombre.setText(tablaPersonal.getValueAt(fila, 1) .toString());
        txtApellido.setText(tablaPersonal.getValueAt(fila, 2) .toString());
        txtCorreo.setText(tablaPersonal.getValueAt(fila, 3) .toString());
        txtFecha.setText(tablaPersonal.getValueAt(fila, 4) .toString());
        
        String sexo = (tablaPersonal.getValueAt(fila, 5) .toString());
        
        if(sexo.equals("M")){
            radioMujer.setSelected(true);
            radioHombre.setSelected(false);
            
        }
          if(sexo.equals("H")){
              radioMujer.setSelected(false);
              radioHombre.setSelected(true);
          }
    }//GEN-LAST:event_tablaPersonalMouseClicked

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        
        int result = JOptionPane.showConfirmDialog(null, "Eliminar el registro?", "Eliminar", JOptionPane.YES_NO_OPTION);
        System.out.println("Resultado" + result);
        
        if(result== 0){
            dao.eliminar(Integer.valueOf(lbId.getText()));
        
            consultarPersonal();
            limpiarControles();
        }
        
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int result = JOptionPane.showConfirmDialog(null, "Actualizar el registro?", "Actualizar", JOptionPane.YES_NO_OPTION);
        System.out.println("Resultado" + result);
        
        if(result== 0){
            crearObjetoPersona();
            dao.actualizar(persona);
            consultarPersonal();
            limpiarControles();
        }
        
    }//GEN-LAST:event_btnActualizarActionPerformed
    public void limpiarControles(){
         lbId.setText("");
         txtNombre.setText("");
         txtApellido.setText("");
         txtCorreo.setText("");
         radioMujer.setSelected(false);
         radioHombre.setSelected(true);
    }
    
    public void crearObjetoPersona(){   
        
        int id = 0;
        if(!lbId.getText().equals("0")){
            id = Integer.valueOf(lbId.getText());
        }
        String nombre = txtNombre.getText();
        String apellido = txtApellido.getText();
        String correo = txtCorreo.getText();
        String sexo = "";
        if(radioMujer.isSelected()){
            sexo = "M";
        }
        if(radioHombre.isSelected()){
            sexo = "H";
        }
        String fecha = txtFecha.getText();
        
        
        persona = new Personal(id,nombre,apellido, correo, fecha, sexo);
        
        //dao.guardar(persona);
        //consultarPersonal();
    }
    public final void consultarPersonal(){
        
        try{
            modelo.setRowCount(0);
            for(Personal p : dao.consultar()){
                //System.out.println(p.toString());
                
                modelo.addRow(new Object[]{p.getIdPersona(),p.getNombre(),p.getApellido(),p.getCorreo(),p.getFecha(),p.getSexo(),
                    p.calcularEdad()});
            }
            
        }catch(Exception ex){
            System.out.println("Error: "+ ex.toString());
        }
    }
    
    
